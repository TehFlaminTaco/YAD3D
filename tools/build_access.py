#!/usr/bin/env python3
"""Write src/shared/accessdata.js: the regions of the station's accesses and what each is called (access.dm get_region_accesses, get_region_accesses_name, get_access_desc), for the airlock
electronics' menu. The numbers are the game's own (data/jobs.json `access`).  Run: python tools/build_access.py"""
import json
import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
DM = os.path.join(ROOT, '_src', 'tg2020', 'code', 'modules', 'jobs', 'access.dm')
JOBS = os.path.join(ROOT, 'data', 'jobs.json')
OUT = os.path.join(ROOT, 'src', 'shared', 'accessdata.js')

src = open(DM, encoding='utf-8').read()
number = {name: int(n) for n, name in json.load(open(JOBS))['access'].items()}


def region(code):
    m = re.search(r'/proc/get_region_accesses\(code\)\s*switch\(code\)(.*?)/proc/get_region_accesses_name', src, re.S)
    body = m.group(1)
    mm = re.search(r'if\(%d\)[^\n]*\n\s*return list\((.*?)\)\n' % code, body, re.S)
    return [x.strip()[len('ACCESS_'):] for x in mm.group(1).split(',') if x.strip().startswith('ACCESS_')]


names = {}
for m in re.finditer(r'if\(ACCESS_(\w+)\)\s*return "([^"]*)"', src):
    names[m.group(1)] = m.group(2)
region_names = {}
m = re.search(r'/proc/get_region_accesses_name\(code\)(.*?)/proc/get_access_desc', src, re.S)
for mm in re.finditer(r'if\((\d)\)[^\n]*\n\s*return "([^"]*)"', m.group(1)):
    region_names[int(mm.group(1))] = mm.group(2)

regions = []
for code in range(1, 8):
    accesses = []
    for a in region(code):
        if a in number and a in names:
            accesses.append([number[a], names[a]])
    regions.append({'name': region_names[code], 'accesses': accesses})

NL = chr(10)
lines = ['// The accesses an airlock can ask for, by region, and what each is called (generated by tools/build_access.py from access.dm: do not edit by hand).',
         'export const ACCESS_REGIONS = [']
for r in regions:
    lines.append("  { name: %s, accesses: [%s] }," % (json.dumps(r['name']), ', '.join('[%d, %s]' % (n, json.dumps(d)) for n, d in r['accesses'])))
lines.append('];')
with open(OUT, 'w', encoding='utf-8', newline=NL) as f:
    f.write(NL.join(lines) + NL)
print('wrote', OUT, sum(len(r['accesses']) for r in regions), 'accesses')
